    /// Если Money.TryCreate провалится — тест провалится (что исключено при правильных входных данных)
    let expectRubleSpelling rubles kopecks expected =
        match Money.TryCreate(rubles, kopecks) with
        | Ok money ->
            let actual = MoneyToWords.toWords money
            test <@ actual = expected @>
        | Error error ->
            test <@ false @>  // Это не должно случиться при валидных входах

