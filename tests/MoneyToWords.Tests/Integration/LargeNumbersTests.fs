    let expectWords rubles kopecks expected =
        match Money.TryCreate(rubles, kopecks) with
        | Ok money ->
            let actual = MoneyToWords.toWords money
            test <@ actual = expected @>
        | Error _ ->
            test <@ false @>  // Это не должно произойти при валидных входах

