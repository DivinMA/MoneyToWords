    let ``0.11 → ноль рублей и одиннадцать копеек`` () =
        expectWords 0L 11 "ноль рублей и одиннадцать копеек"

    [<Fact>]
    let ``0.21 → ноль рублей и двадцать одна копейка`` () =
        expectWords 0L 21 "ноль рублей и двадцать одна копейка"

    [<Fact>]
    let ``0.99 → ноль рублей и девяносто девять копеек`` () =
        expectWords 0L 99 "ноль рублей и девяносто девять копеек"

    /// === Единицы рублей + разные копейки ===

    [<Fact>]
    let ``1.00 → один рубль`` () =
        expectWords 1L 0 "один рубль"

    [<Fact>]
    let ``1.01 → один рубль и одна копейка`` () =
        expectWords 1L 1 "один рубль и одна копейка"

    [<Fact>]
    let ``1.02 → один рубль и две копейки`` () =
        expectWords 1L 2 "один рубль и две копейки"

    [<Fact>]
    let ``1.05 → один рубль и пять копеек`` () =
        expectWords 1L 5 "один рубль и пять копеек"

    [<Fact>]
