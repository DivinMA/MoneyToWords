namespace MoneyToWords.Tests

open Swensen.Unquote
open Xunit
open MoneyToWords.Domain
open MoneyToWords.Presentation

module MoneyToWordsTests =

    /// Вспомогательная функция: безопасное создание Money и сравнение результата
    let expectWords rubles kopecks expected =
        match Money.TryCreate(rubles, kopecks) with
        | Ok money ->
            let actual = MoneyToWords.toWords money
            test <@ actual = expected @>
        | Error _ ->
            test <@ false @>  // Это не должно произойти при валидных входах

    /// === Минимальные значения ===

    [<Fact>]
    let ``0.00 → ноль рублей`` () =
        expectWords 0L 0 "ноль рублей"

    [<Fact>]
    let ``0.01 → ноль рублей и одна копейка`` () =
        expectWords 0L 1 "ноль рублей и одна копейка"

    [<Fact>]
    let ``0.02 → ноль рублей и две копейки`` () =
        expectWords 0L 2 "ноль рублей и две копейки"

    [<Fact>]
    let ``0.05 → ноль рублей и пять копеек`` () =
        expectWords 0L 5 "ноль рублей и пять копеек"

    [<Fact>]
    let ``0.10 → ноль рублей и десять копеек`` () =
        expectWords 0L 10 "ноль рублей и десять копеек"

