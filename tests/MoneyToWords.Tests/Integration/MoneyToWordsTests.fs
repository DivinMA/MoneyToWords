    let ``2.01 → два рубля и одна копейка`` () =
        expectWords 2L 1 "два рубля и одна копейка"

    [<Fact>]
    let ``2.99 → два рубля и девяносто девять копеек`` () =
        expectWords 2L 99 "два рубля и девяносто девять копеек"

