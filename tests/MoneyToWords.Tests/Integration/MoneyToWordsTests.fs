    /// === 20, 21, 22, 25, 29, 30, 90, 99 рублей + копейки ===

    [<Fact>]
    let ``20.01 → двадцать рублей и одна копейка`` () =
        expectWords 20L 1 "двадцать рублей и одна копейка"

    [<Fact>]
    let ``21.01 → двадцать один рубль и одна копейка`` () =
        expectWords 21L 1 "двадцать один рубль и одна копейка"

    [<Fact>]
    let ``22.01 → двадцать два рубля и одна копейка`` () =
        expectWords 22L 1 "двадцать два рубля и одна копейка"

    [<Fact>]
    let ``25.01 → двадцать пять рублей и одна копейка`` () =
        expectWords 25L 1 "двадцать пять рублей и одна копейка"

