    /// === Сотни: 100, 101, 111, 121, 200, 500, 900, 999 ===

    [<Fact>]
    let ``100.01 → сто рублей и одна копейка`` () =
        expectWords 100L 1 "сто рублей и одна копейка"

    [<Fact>]
    let ``101.01 → сто один рубль и одна копейка`` () =
        expectWords 101L 1 "сто один рубль и одна копейка"

    [<Fact>]
    let ``111.01 → сто одиннадцать рублей и одна копейка`` () =
        expectWords 111L 1 "сто одиннадцать рублей и одна копейка"

    [<Fact>]
    let ``121.01 → сто двадцать один рубль и одна копейка`` () =
        expectWords 121L 1 "сто двадцать один рубль и одна копейка"

    [<Fact>]
    let ``200.99 → двести рублей и девяносто девять копеек`` () =
        expectWords 200L 99 "двести рублей и девяносто девять копеек"

    [<Fact>]
    let ``500.01 → пятьсот рублей и одна копейка`` () =
        expectWords 500L 1 "пятьсот рублей и одна копейка"

    [<Fact>]
    let ``900.01 → девятьсот рублей и одна копейка`` () =
        expectWords 900L 1 "девятьсот рублей и одна копейка"

    [<Fact>]
    let ``999.99 → девятьсот девяносто девять рублей и девяносто девять копеек`` () =
        expectWords 999L 99 "девятьсот девяносто девять рублей и девяносто девять копеек"

    /// === Тысячи: 1_000, 1_001, 1_100, 1_101, 1_111 ===

    [<Fact>]
    let ``1_000.01 → одна тысяча рублей и одна копейка`` () =
        expectWords 1_000L 1 "одна тысяча рублей и одна копейка"

    [<Fact>]
    let ``1_001.01 → одна тысяча один рубль и одна копейка`` () =
        expectWords 1_001L 1 "одна тысяча один рубль и одна копейка"

    [<Fact>]
    let ``1_100.01 → одна тысяча сто рублей и одна копейка`` () =
        expectWords 1_100L 1 "одна тысяча сто рублей и одна копейка"

    [<Fact>]
    let ``1_101.01 → одна тысяча сто один рубль и одна копейка`` () =
        expectWords 1_101L 1 "одна тысяча сто один рубль и одна копейка"

