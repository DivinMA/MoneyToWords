        expectWords 1_111L 99 "одна тысяча сто одиннадцать рублей и девяносто девять копеек"

    /// === Максимальные значения ===

    [<Fact>]
    let ``999_999_999_999_999.00 → девятьсот девяносто девять триллионов девятьсот девяносто девять миллиардов девятьсот девяносто девять миллионов девятьсот девяносто девять тысяч девятьсот девяносто девять рублей`` () =
        expectWords 999_999_999_999_999L 0
            "девятьсот девяносто девять триллионов девятьсот девяносто девять миллиардов девятьсот девяносто девять миллионов девятьсот девяносто девять тысяч девятьсот девяносто девять рублей"

    [<Fact>]
    let ``999_999_999_999_999.01 → девятьсот девяносто девять триллионов ... и одна копейка`` () =
        expectWords 999_999_999_999_999L 1
            "девятьсот девяносто девять триллионов девятьсот девяносто девять миллиардов девятьсот девяносто девять миллионов девятьсот девяносто девять тысяч девятьсот девяносто девять рублей и одна копейка"

